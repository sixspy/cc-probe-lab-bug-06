"""待删齐套 · 甲组：打待删后齐套数必须下降，空正式集不得满。

契约（题面失败测甲）：
- 只留待删影子行时，齐套灯仍满 → 红。
- 打待删后，齐套计数须按「未删正式集」读，影子行不得计入。
"""
from __future__ import annotations

import pytest

from app.services import 目录, 装载, 结栏


def _装(批次: str, 站: str = "站-河东", 指标: str = "PM25", 读数: float = 30.0) -> dict:
    return 装载.装一批(
        {
            "批次编号": 批次,
            "报文": [
                {
                    "报文编号": f"{批次}-1",
                    "站点键": 站,
                    "指标键": 指标,
                    "读数": 读数,
                    "观测时": "2026-11-24T08:10:00Z",
                }
            ],
        }
    )


def _造两行() -> tuple[str, str]:
    _装("甲a", "站-河东")
    _装("甲b", "站-北岭")
    结栏.结当前栏()
    rows = 目录.汇总列表()
    assert len(rows) == 2
    return rows[0]["汇总编号"], rows[1]["汇总编号"]


def test_齐套数排除待删影子行():
    a, b = _造两行()
    assert 目录.汇总齐套数() == 2

    目录.打待删(a, "甲测")

    # 正式集只剩 b；影子 a 不得再计入齐套。
    assert 目录.汇总齐套数() == 1
    assert len(目录.汇总列表()) == 1
    assert len(目录.归档列表()) == 1
    assert 目录.归档列表()[0]["汇总编号"] == a


def test_只留待删影子行时齐套灯熄灭():
    a, b = _造两行()
    目录.打待删(a, "甲测")
    目录.打待删(b, "甲测")

    assert 目录.汇总齐套数() == 0
    assert 目录.汇总列表() == []
    assert len(目录.归档列表()) == 2

    灯 = 目录.齐套灯()
    assert 灯["齐套"] is False, "正式集为空仍亮齐套 → 假满"
    # 修复后芯片随正式集落成「待删仍计」，不再假绿。
    assert 灯["假满"] is False
    assert 灯["正式行数"] == 0
    assert 灯["影子行数"] == 2


def test_半修只亮灯不改计数仍红():
    a, b = _造两行()
    目录.打待删(a, "甲测")
    目录.打待删(b, "甲测")

    # 顶层面板芯片被强行点亮，也不能改变齐套判定。
    目录.强行亮灯()

    assert 目录.齐套灯()["齐套"] is False
    assert 目录.齐套灯()["假满"] is True
    assert 目录.汇总齐套数() == 0


def test_空正式集可从归档对账区分():
    a, b = _造两行()
    目录.打待删(a, "甲测")
    目录.打待删(b, "甲测")

    对 = 目录.汇总对账()
    assert 对["正式"]["行数"] == 0
    assert 对["归档"]["行数"] == 2
    assert 对["正式"]["报文数"] == 0
    assert 对["归档"]["待删报文数"] > 0
    # 正式集合为空时，不能因为“归档里有数”而判齐套。
    assert 对["正式齐套"] is False
