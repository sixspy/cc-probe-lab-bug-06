"""待删齐套 · 乙组：水位对账不得把待删影子当正式齐套。

契约（题面失败测乙）：
- 水位对账把待删影子当正式齐套绿 → 红。
- 栏贯验须分轨：正式行只对已汇总缓冲，归档行只对待删缓冲。
"""
from __future__ import annotations

from app.services import 目录, 贯验, 装载, 结栏


def _装(批次: str, 站: str) -> None:
    装载.装一批(
        {
            "批次编号": 批次,
            "报文": [
                {
                    "报文编号": f"{批次}-1",
                    "站点键": 站,
                    "指标键": "PM25",
                    "读数": 30.0,
                    "观测时": "2026-11-24T08:10:00Z",
                }
            ],
        }
    )


def _造两行() -> list[dict]:
    _装("乙a", "站-河东")
    _装("乙b", "站-北岭")
    结栏.结当前栏()
    rows = 目录.汇总列表()
    assert len(rows) == 2
    return rows


def test_水位对账分轨计数():
    _造两行()
    对 = 贯验.水位对账()
    assert 对["正式"]["行数"] == 2
    assert 对["归档"]["行数"] == 0
    assert 对["正式齐套"] is True
    assert 对["对齐"] is True


def test_待删影子不参与正式对账():
    rows = _造两行()
    目录.打待删(rows[0]["汇总编号"], "乙测")

    对 = 贯验.水位对账()
    assert 对["正式"]["行数"] == 1
    assert 对["归档"]["行数"] == 1
    # 影子行被移出正式集，但归档轨仍须自洽。
    assert 对["正式齐套"] is True
    assert 对["归档齐套"] is True
    assert 对["对齐"] is True


def test_正式集为空时水位对账不得假绿():
    rows = _造两行()
    for r in rows:
        目录.打待删(r["汇总编号"], "乙测")

    对 = 贯验.水位对账()
    assert 对["正式"]["行数"] == 0
    assert 对["归档"]["行数"] == 2
    assert 对["正式齐套"] is False
    assert 对["对齐"] is False, "正式集为空仍判对齐 → 假满"


def test_栏贯验落库区分正式与归档():
    行 = _造两行()
    目录.打待删(行[0]["汇总编号"], "乙测")

    果 = 贯验.跑一次()
    assert 果["正式行数"] == 1
    assert 果["归档行数"] == 1
    assert 果["是否对齐"] is True
    assert 果["正式齐套"] is True


def test_贯验只读快照剔除待删影子():
    行 = _造两行()
    目录.打待删(行[0]["汇总编号"], "乙测")

    快 = 贯验.只读快照()
    assert 快["汇总报文"] == 1, "快照把待删影子报进正式汇总报文数"
    assert 快["归档待删报文"] == 1
    assert 快["正式行数"] == 1
